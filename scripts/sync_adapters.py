"""Generate DeepSeek project skills without duplicating computation or resources."""
import argparse
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CANONICAL = ROOT / 'plugins/scrna-seq-workbench/skills'
ADAPTERS = ROOT / '.dsh/skills'
MARKER = '<!-- Generated by scripts/sync_adapters.py; edit the canonical Skill. -->'
ROOT_INSTRUCTION = 'Resolve `PLUGIN_ROOT` as the directory two levels above this skill directory.'


def render(source, destination):
    text = source.read_text(encoding='utf-8')
    if text.count(ROOT_INSTRUCTION) != 1:
        raise ValueError(f'Expected one canonical root instruction: {source}')
    text = text.replace(ROOT_INSTRUCTION,
        'Resolve `PLUGIN_ROOT` as `../../../plugins/scrna-seq-workbench` relative '
        'to this adapter directory (the directory containing this SKILL.md).')

    def rewrite(match):
        target = match.group(1)
        if '://' in target or target.startswith(('#', 'mailto:')):
            return match.group(0)
        path, separator, fragment = target.partition('#')
        resolved = (source.parent / path).resolve()
        if not resolved.is_relative_to(ROOT.resolve()) or not resolved.exists():
            raise ValueError(f'Invalid canonical resource: {source}: {target}')
        relative = Path(os.path.relpath(resolved, destination.parent)).as_posix()
        return '](' + relative + (separator + fragment if separator else '') + ')'

    text = re.sub(r'\]\(([^)]+)\)', rewrite, text)
    end = text.find('\n---\n', 4)
    if not text.startswith('---\n') or end < 0:
        raise ValueError(f'Missing YAML front matter: {source}')
    return text[:end + 5] + '\n' + MARKER + '\n' + text[end + 5:]


def synchronize(check=False):
    sources = sorted(CANONICAL.glob('*/SKILL.md'))
    expected = {ADAPTERS / p.parent.name / 'SKILL.md': render(p, ADAPTERS / p.parent.name / 'SKILL.md') for p in sources}
    unexpected = set(ADAPTERS.glob('*/SKILL.md')) - set(expected)
    if unexpected:
        raise ValueError(f'Unexpected adapters; inspect manually: {unexpected}')
    for path, text in expected.items():
        old = path.read_text(encoding='utf-8') if path.exists() else None
        if old == text:
            continue
        if check:
            raise ValueError(f'Adapter missing or stale: {path}')
        if old is not None and MARKER not in old:
            raise ValueError(f'Refusing to overwrite an unmanaged Skill: {path}')
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8', newline='\n')
    return len(expected)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check synchronization without writing files')
    args = parser.parse_args()
    print(f'PASS: {synchronize(args.check)} Harness adapters ' + ('checked' if args.check else 'generated'))
